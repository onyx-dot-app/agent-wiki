class EntityTypeTaxonomy(Base):
    """A derived entity-type taxonomy, kept as a history rather than a current value.

    Entity types key facts by entity, so a re-derivation that renames a type would orphan
    every row keyed under the old name. Rows are therefore append-only and one is marked
    ``active``: a new derivation inserts and flips the flag, and the superseded taxonomy
    stays resolvable for anything still pointing at it.

    ``types`` and ``provenance`` are free-form JSONB. The shape is owned by
    ``app.ingest.entity_types`` (which produces it) rather than by a column layout, because
    it is read whole and never queried by field — and because pinning it would mean a
    migration every time a derivation stage learns to record something new.
    """

    __tablename__ = "entity_type_taxonomies"

    # Monotonic, and what a consumer records to say which taxonomy it keyed facts under.
    # SERIAL rather than an application-computed counter: "SELECT max + 1" then INSERT is
    # not atomic, so two concurrent derivations could pick the same number.
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    # Exactly one row is active. Enforced by a partial unique index, not by convention.
    active: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("FALSE"))
    # sha256 over the corpus this was derived from. Answers "has the wiki moved far enough
    # to warrant re-deriving?", which nothing else can reconstruct after the fact.
    corpus_fingerprint: Mapped[str] = mapped_column(Text, nullable=False)
    # The type list: [{name, definition, examples, n_referents, n_docs}, ...]
    types: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, nullable=False)
    # Models, thresholds, and the funnel counts. Kept so a human can judge whether a
    # derivation is trustworthy without re-running it — a merge that collapsed 75 types to 9
    # looks very different from one that left 75 standing.
    provenance: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'{}'::jsonb")
    )
    stats: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'{}'::jsonb")
    )
    triggered_by: Mapped[str | None] = mapped_column(
        Text, ForeignKey("users.id", ondelete="SET NULL")
    )
    created_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)

    __table_args__ = (
        Index(
            "uq_entity_type_taxonomies_active",
            "active",
            unique=True,
            postgresql_where=text("active"),
        ),
    )


class PageNeeds(Base):
    """What one wiki page keeps track of — its information needs.

    Current-valued, unlike ``entity_type_taxonomies``: a page's needs describe that page as it is
    now, so re-extracting replaces them. There is nothing to orphan, because nothing keys
    facts by a need.

    Keyed by ``doc_id``, not path. Extraction costs an LLM call per page, and ``wiki_doc_ids``
    re-keys its path in place on a move — so a rename keeps its needs instead of presenting as
    a new page whose needs must be bought again and an old path to prune. Deliberately unlike
    ``PageEmbedding``, which is path-keyed; that difference is affordable there and is not here.

    There is no ``path`` column on purpose. After a move the row is intentionally NOT stale, so
    a denormalized path would never be refreshed — it would go stale on the first rename and
    stay that way. The live path comes from ``wiki_doc_ids`` instead.

    Together those two choices mean this table needs no wiki lifecycle hook. A move re-keys the
    doc-id row, so the joined path follows it and the needs stay valid. A delete tombstones that
    row, and reads exclude tombstoned pages (``page_needs.load_all``) — so a trashed page's needs
    stop being visible at once rather than at the next extraction, while the row itself survives
    long enough for a restore to get them back for free.

    ``content_sha256`` / ``model`` / ``entity_type_taxonomy_id`` together are the re-extract guard, and
    all three belong in it. The hash catches an edited page; ``model`` catches a model change,
    which changes what gets extracted; ``entity_type_taxonomy_id`` catches a re-derived taxonomy, whose
    type menu the entity labels were drawn from. A run that skipped a page because only the
    taxonomy moved would leave behind entity types the current taxonomy no longer defines.
    """

    __tablename__ = "page_needs"

    # The page's stable identity. CASCADE is a formality — deletes tombstone the row rather
    # than dropping it (see ``WikiDocId``), so this cannot orphan; it states the intent for the
    # case where an id genuinely goes away, since needs are meaningless without the page.
    doc_id: Mapped[str] = mapped_column(
        Text, ForeignKey("wiki_doc_ids.id", ondelete="CASCADE"), primary_key=True
    )
    # sha256 of the page body extracted from.
    content_sha256: Mapped[str] = mapped_column(Text, nullable=False)
    # The completion model used. Empty string means "the deployment default", which is what
    # the extractor records when the caller does not pin one.
    model: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    # The taxonomy whose type menu these entity labels came from. SET NULL rather than
    # CASCADE: losing the taxonomy row must not delete a page's needs, only the ability to
    # resolve their type names — and NULL here reads correctly as "types unresolvable", which
    # makes the page stale and gets it re-extracted.
    entity_type_taxonomy_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("entity_type_taxonomies.id", ondelete="SET NULL")
    )
    # [{need_name, need_kind, description, detail_level, update_instruction, current_content,
    #   entities: [{canonical_name, entity_type, primary}], focus}, ...]
    # JSONB and free-form for the same reason as ``EntityTypeTaxonomy.types``: the shape is owned
    # by ``app.ingest.needs``, read whole, and never queried by field.
    needs: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, nullable=False)
    updated_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)

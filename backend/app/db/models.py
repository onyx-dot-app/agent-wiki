# --------------------------------------------------------------------------- #
# Co-editing — live shared editing sessions (the Postgres editing buffer)     #
# --------------------------------------------------------------------------- #
#
# One live session per page (path-keyed): multiple humans join the same
# session and converge on a single shared Yjs document (a CRDT — merging is
# structural, not compare-and-swap). A single-user edit is just a
# 1-participant session, which is how the per-user draft will eventually
# fold into this model. The session periodically checkpoints to git through
# ``commit_and_fan_out`` — ``base_sha`` is the HEAD it last merged against,
# the merge base for the checkpoint 3-way merge. This store is the editing
# *buffer* only; git stays the source of truth for committed pages.


class CoeditSession(Base):
    __tablename__ = "coedit_sessions"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    # Canonical wiki-relative path (no leading slash), per
    # ``app.wiki.filesystem.safe_rel_path``. At most one *active* session per
    # path (enforced by the partial unique index below).
    path: Mapped[str] = mapped_column(Text, nullable=False)
    # The Yjs doc's last-persisted binary state (``Doc.get_update()``/
    # equivalent snapshot) at ``ydoc_snapshot_seq`` — set once at session
    # creation (seeded from the page's HEAD, seq 0) and advanced by every
    # checkpoint after that. With the log, this pair *is* the document: any
    # process rebuilds a throwaway ``Doc`` from this snapshot plus every
    # ``CoeditUpdate`` in ``(ydoc_snapshot_seq, ydoc_seq]`` — see
    # ``app/wiki/coedit_live.py`` and ``app/wiki/coedit_checkpoint.py``.
    ydoc_snapshot: Mapped[bytes | None] = mapped_column(LargeBinary)
    # The ``ydoc_seq`` the current ``ydoc_snapshot`` bytes represent —
    # updates with ``seq > ydoc_snapshot_seq`` are exactly the ones a
    # checkpoint still needs to replay onto the snapshot to reach current
    # state.
    ydoc_snapshot_seq: Mapped[int] = mapped_column(
        BigInteger, nullable=False, server_default=text("0")
    )
    # The markdown ``ydoc_snapshot`` represents — the checkpoint diff base
    # (``markdown_splice.checkpoint_body``'s ``base_body``), kept in lockstep
    # with the snapshot everywhere it advances. Content-equal to what the
    # snapshot reconstructs to, not byte-equal to whatever an author typed:
    # the codec normalizes block terminators, so a round trip is stable but not
    # necessarily identical to the input. Deliberately *not* re-derived from a
    # git read at ``base_sha``: a live-rebase fold has no git commit of its own,
    # so ``base_sha`` can't always resolve to the content the snapshot
    # actually represents the way a real commit ref can.
    ydoc_snapshot_body: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    # Monotonic sequence, bumped on every applied Yjs update. Clients/late
    # joiners use it to ask "updates since N" for catch-up.
    ydoc_seq: Mapped[int] = mapped_column(BigInteger, nullable=False, server_default=text("0"))
    # The ``ydoc_seq`` at the last checkpoint — the doc is "dirty" (has
    # uncommitted edits) when ``ydoc_seq > ydoc_checkpointed_seq``. Lets the
    # checkpoint scan skip clean sessions instead of re-committing them.
    ydoc_checkpointed_seq: Mapped[int] = mapped_column(
        BigInteger, nullable=False, server_default=text("0")
    )
    # Git HEAD the doc was last checkpointed against — the merge base for the
    # checkpoint 3-way merge. Null until the session is seeded from a page's
    # HEAD (or, for a brand-new page, until the first checkpoint).
    base_sha: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'active'"))
    created_at: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=_NOW_TEXT_DEFAULT
    )
    updated_at: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=_NOW_TEXT_DEFAULT
    )
    last_checkpoint_at: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (
        CheckConstraint(
            "status IN ('active', 'closed')", name="coedit_sessions_status_check"
        ),
        # At most one active session per page. A partial unique index lets
        # closed sessions accumulate as history without blocking a fresh one.
        Index(
            "idx_coedit_sessions_active_path",
            "path",
            unique=True,
            postgresql_where=text("status = 'active'"),
        ),
    )



class Trigger(Base):
    __tablename__ = "triggers"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    owner_user_id: Mapped[str] = mapped_column(
        Text, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    scope_path: Mapped[str] = mapped_column(Text, nullable=False)
    kind: Mapped[str] = mapped_column(Text, nullable=False)        # "delta" | "schedule"
    nl_description: Mapped[str] = mapped_column(Text, nullable=False)
    action_json: Mapped[str] = mapped_column(Text, nullable=False)
    schedule_cron: Mapped[str | None] = mapped_column(Text)
    enabled: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("TRUE"))
    file_path: Mapped[str | None] = mapped_column(Text)
    last_edited_at: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)


# --------------------------------------------------------------------------- #
# Audit log                                                                   #
# --------------------------------------------------------------------------- #


class Event(Base):
    __tablename__ = "events"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    ts: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)
    kind: Mapped[str] = mapped_column(Text, nullable=False)
    actor: Mapped[str | None] = mapped_column(Text)
    target: Mapped[str | None] = mapped_column(Text)
    payload_json: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("'{}'"))

    __table_args__ = (
        Index("idx_events_ts", "ts"),
        Index("idx_events_kind_ts", "kind", "ts"),
    )


# --------------------------------------------------------------------------- #
# BM25 search index (pg_textsearch)                                           #
# --------------------------------------------------------------------------- #


class DocumentFts(Base):
    """Wiki search index — title + body indexed via pg_textsearch.

    The BM25 access method (``USING bm25``) is registered by the
    extension; the ``0001_initial`` migration runs
    ``CREATE EXTENSION pg_textsearch`` before ``Base.metadata.create_all``
    so the index DDL succeeds.
    """

    __tablename__ = "documents_fts"

    doc_id: Mapped[str] = mapped_column(Text, primary_key=True)
    path: Mapped[str] = mapped_column(Text, nullable=False)
    title: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    body: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))

    __table_args__ = (
        Index(
            "documents_fts_bm25",
            text("(coalesce(title, '') || ' ' || coalesce(body, ''))"),
            postgresql_using="bm25",
            # Quote the value explicitly — SQLAlchemy's WITH renderer passes
            # the dict value through as-is, and pg_textsearch's examples all
            # use the quoted form (``text_config = 'english'``).
            postgresql_with={"text_config": "'english'"},
        ),
    )


# --------------------------------------------------------------------------- #
# Single-row settings tables — id=1 always                                    #
# --------------------------------------------------------------------------- #


class LLMSettings(Base):
    __tablename__ = "llm_settings"

    # ``id`` is always 1 — the CHECK below + the singleton constraint enforce
    # that. Mark autoincrement=False so SQLAlchemy doesn't synthesize a
    # SERIAL sequence we'd never read from.
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=False)
    provider: Mapped[str] = mapped_column(Text, nullable=False)
    model: Mapped[str] = mapped_column(Text, nullable=False)
    anthropic_api_key: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    openai_api_key: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    gemini_api_key: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    ollama_base_url: Mapped[str] = mapped_column(Text, nullable=False, server_default=text("''"))
    updated_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)

    __table_args__ = (CheckConstraint("id = 1", name="llm_settings_singleton"),)



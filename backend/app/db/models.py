# scheduler can survive restarts without silently dropping or stampeding      #
# missed fires. See app/tasks/queue.py:_run_periodic_scheduler.               #
# --------------------------------------------------------------------------- #


class CronState(Base):
    __tablename__ = "cron_state"

    queue_name: Mapped[str] = mapped_column(Text, primary_key=True)
    task_name: Mapped[str] = mapped_column(Text, primary_key=True)
    last_fired_at: Mapped[str | None] = mapped_column(Text)

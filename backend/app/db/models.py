"""SQLAlchemy ORM models — the source of truth for the app's schema.

``init_db()`` in ``app.db.session`` runs ``alembic upgrade head``;
schema changes flow through autogenerated migration files in
``app/db/migrations/versions/``. So when you edit a model here, also
run ``cd backend && alembic revision --autogenerate -m "<slug>"`` and
review the emitted diff before committing. The bootstrap migration
``0001_initial`` materializes the entire current schema via
``Base.metadata.create_all`` — every migration after it is an explicit
``op.alter_table`` / ``op.add_column`` diff.

Keep these models *narrow* — they describe DB shape. HTTP request /
response shapes belong in ``app/models/`` (pydantic). Repos return
dicts derived from these objects so callers don't depend on the ORM.
"""

from __future__ import annotations

from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Float,
    ForeignKey,
    Index,
    Integer,
    LargeBinary,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.db.crypto import EncryptedString

# Default for TEXT timestamp columns. Stored as ISO-formatted strings so
# Python-side ISO comparisons (e.g. ``expires_at > _iso(_now())``) work
# without per-call casts. Switching these to ``TIMESTAMPTZ`` would mean
# updating every site that passes / serializes the value — not worth it
# for the marginal type safety.
_NOW_TEXT_DEFAULT = text("to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")


class Base(DeclarativeBase):
    pass



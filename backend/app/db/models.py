"""SQLAlchemy ORM models — the source of truth for the app's schema.

``init_db()`` in ``app.db.session`` runs ``alembic upgrade head``;
schema changes flow through autogenerated migration files in
``app/db/migrations/versions/``. So when you edit a model here, also
run ``cd backend && alembic revision --autogenerate -m "<slug>"`` and
review the emitted diff before committing. The bootstrap migration
``0001_initial`` materializes the entire current schema via
``Base.metadata.create_all`` — every migration after it is an explicit
``op.alter_table`` / ``op.add_column`` diff. Postgres-specific bits
that ORM declarations can't express (extension creation, pgmq queue
creation) also live in ``0001_initial``.

Keep these models *narrow* — they describe DB shape. HTTP request /
response shapes belong in ``app/models/`` (pydantic). Repos return
dicts derived from these objects so callers don't depend on the ORM.
"""
from __future__ import annotations

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    ForeignKey,
    Index,
    Integer,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Default for TEXT timestamp columns. Stored as ISO-formatted strings so
# Python-side ISO comparisons (e.g. ``expires_at > _iso(_now())``) work
# without per-call casts. Switching these to ``TIMESTAMPTZ`` would mean
# updating every site that passes / serializes the value — not worth it
# for the marginal type safety.
_NOW_TEXT_DEFAULT = text("to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')")


class Base(DeclarativeBase):
    pass


# --------------------------------------------------------------------------- #
# Users + auth                                                                #
# --------------------------------------------------------------------------- #


class User(Base):
    __tablename__ = "users"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    email: Mapped[str] = mapped_column(Text, unique=True, nullable=False)
    name: Mapped[str | None] = mapped_column(Text)
    # Null when AUTH_MODE=oidc.
    password_hash: Mapped[str | None] = mapped_column(Text)
    is_admin: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("FALSE"))
    created_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)


class McpConnection(Base):
    __tablename__ = "mcp_connections"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    user_id: Mapped[str] = mapped_column(
        Text, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    name: Mapped[str] = mapped_column(Text, nullable=False)
    transport: Mapped[str] = mapped_column(Text, nullable=False)   # "stdio" | "http"
    config_json: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)


# --------------------------------------------------------------------------- #
# Documents (metadata) — canonical content lives in git                       #
# --------------------------------------------------------------------------- #


class Document(Base):
    __tablename__ = "documents"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    path: Mapped[str] = mapped_column(Text, unique=True, nullable=False)
    title: Mapped[str | None] = mapped_column(Text)
    updated_at: Mapped[str] = mapped_column(Text, nullable=False, server_default=_NOW_TEXT_DEFAULT)


# --------------------------------------------------------------------------- #
# Triggers — git-backed YAML is the source of truth; this is a lookup cache   #
